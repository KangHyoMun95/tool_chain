-- Initial schema, derived from the "Data model" section of CLAUDE.md.

CREATE TABLE roles (
    role_id   SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE users (
    user_id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    phone_number  VARCHAR(20)  NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL, -- always a hash
    role_id       SMALLINT     NOT NULL REFERENCES roles (role_id),
    refer_user_id BIGINT       REFERENCES users (user_id), -- direct superior
    balance       BIGINT       NOT NULL DEFAULT 0 CHECK (balance >= 0),
    status        VARCHAR(20)  NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive', 'deleted')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_refer_user_id ON users (refer_user_id);
CREATE INDEX idx_users_role_id ON users (role_id);

CREATE TABLE lobbies (
    lobby_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    lobby_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    status     VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DEACTIVE', 'ARCHIVE'))
);

CREATE TABLE categories (
    category_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(255) NOT NULL,
    lobby_id      BIGINT       NOT NULL REFERENCES lobbies (lobby_id),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DEACTIVE', 'ARCHIVE')),
    UNIQUE (lobby_id, category_name)
);

CREATE TABLE streams (
    stream_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stream_name VARCHAR(255) NOT NULL,
    category_id BIGINT       NOT NULL REFERENCES categories (category_id),
    key_id      VARCHAR(768) NOT NULL UNIQUE, -- <lobby>|<category>|<stream>, normalized
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'DEACTIVE', 'ARCHIVE'))
);
CREATE INDEX idx_streams_category_id ON streams (category_id);

CREATE TABLE stream_information (
    stream_information_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stream_id             BIGINT       NOT NULL REFERENCES streams (stream_id),
    streamer_id           VARCHAR(255) NOT NULL -- streamer name (text), not a FK
);
CREATE INDEX idx_stream_information_stream_id ON stream_information (stream_id);

-- IDs of game_sessions and predictions are generated by the application
-- before batching, so there is intentionally no DEFAULT.
CREATE TABLE game_sessions (
    game_session_id UUID PRIMARY KEY,
    stream_id       BIGINT      NOT NULL REFERENCES streams (stream_id),
    road_count      INTEGER,
    result          VARCHAR(50),
    status          VARCHAR(20) NOT NULL DEFAULT 'RUNNING'
        CHECK (status IN ('RUNNING', 'FINISHED', 'CANCELLED')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_game_sessions_stream_created ON game_sessions (stream_id, created_at DESC);

CREATE TABLE predictions (
    prediction_id    UUID PRIMARY KEY,
    stream_id        BIGINT      NOT NULL REFERENCES streams (stream_id),
    game_session_id  UUID        NOT NULL UNIQUE REFERENCES game_sessions (game_session_id),
    predict_result   VARCHAR(50) NOT NULL,
    confidence_score NUMERIC(5, 4),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_predictions_stream_id ON predictions (stream_id);

CREATE TABLE stream_participants (
    stream_participant_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id               BIGINT      NOT NULL REFERENCES users (user_id),
    stream_id             BIGINT      NOT NULL REFERENCES streams (stream_id),
    last_seen_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, stream_id)
);
CREATE INDEX idx_stream_participants_stream_seen ON stream_participants (stream_id, last_seen_at);

CREATE TABLE prediction_subscriptions (
    prediction_subscription_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id                    BIGINT      NOT NULL REFERENCES users (user_id),
    prediction_id              UUID        NOT NULL REFERENCES predictions (prediction_id),
    fee_amount                 BIGINT      NOT NULL CHECK (fee_amount > 0), -- price at charge time
    refunded_at                TIMESTAMPTZ,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (user_id, prediction_id)
);
CREATE INDEX idx_prediction_subscriptions_prediction_id ON prediction_subscriptions (prediction_id);

CREATE TABLE transactions (
    transaction_id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id                      BIGINT      NOT NULL REFERENCES users (user_id),
    predictions_subscriptions_id BIGINT      REFERENCES prediction_subscriptions (prediction_subscription_id),
    transaction_type             VARCHAR(20) NOT NULL
        CHECK (transaction_type IN ('MINT', 'TRANSFER_OUT', 'TRANSFER_IN', 'CHARGE', 'REFUND')),
    amount                       BIGINT      NOT NULL CHECK (amount > 0),
    balance_before               BIGINT      NOT NULL,
    balance_after                BIGINT      NOT NULL,
    created_by                   BIGINT      REFERENCES users (user_id),
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_transactions_user_created ON transactions (user_id, created_at DESC);
CREATE INDEX idx_transactions_subscription_id ON transactions (predictions_subscriptions_id);
